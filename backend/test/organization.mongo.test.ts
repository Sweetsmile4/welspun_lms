import { randomUUID } from 'node:crypto';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { createMongoAdapter } from '../src/platform/database.js';
import { createMongoOrganizationRepository } from '../src/modules/identity/organization/mongo-repository.js';
import { createOrganizationService } from '../src/modules/identity/organization/service.js';
import { organizationScenarios } from './organization-scenarios.js';

const enabled = process.env.RUN_MONGO_INTEGRATION === 'true';
describe.skipIf(!enabled)(
  'real local MongoDB replica-set integration — opt in only',
  () => {
    let adapter: ReturnType<typeof createMongoAdapter>;
    let repository: ReturnType<typeof createMongoOrganizationRepository>;
    beforeAll(async () => {
      if (
        process.env.MONGO_TEST_ALLOW_WRITE !== 'true' ||
        !process.env.MONGO_TEST_URI
      )
        throw new Error(
          'Mongo tests require an explicit local URI and write opt-in',
        );
      const uri = new URL(process.env.MONGO_TEST_URI);
      if (!uri.pathname.startsWith('/welspun_lms_test_'))
        throw new Error(
          'Mongo integration requires an isolated test database prefix',
        );
      uri.pathname = '/welspun_lms_test_' + randomUUID().replaceAll('-', '');
      adapter = createMongoAdapter({
        uri: uri.toString(),
        environment: 'test',
        isolated: true,
      });
      await adapter.connect({ explicitlyAllowConnection: true });
      const hello = await adapter.connection.db!.admin().command({ hello: 1 });
      if (!hello.setName)
        throw new Error(
          'Organization transactions require a replica set; standalone MongoDB is unsupported',
        );
      repository = createMongoOrganizationRepository(adapter.connection);
      await repository.initializeIndexes();
    });
    afterAll(async () => {
      if (adapter) {
        // This database name was generated by this suite, after local-target validation.
        if (adapter.state === 1 && repository)
          await adapter.connection.dropDatabase();
        await adapter.disconnect();
      }
    });
    organizationScenarios(() => repository);
    it('enforces identity and optional-ID indexes at MongoDB level, independent of prechecks', async () => {
      const service = createOrganizationService(repository);
      const { organization } = await service.createOrganization(
        {
          code: 'IDX_' + randomUUID().replaceAll('-', ''),
          name: 'Synthetic index fixture',
          timeZone: 'UTC',
        },
        { actorId: 'synthetic-test' },
      );
      const row = {
        organizationId: organization.id,
        identityIssuer: 'urn:synthetic:issuer',
        identitySubject: 'index-subject',
        displayName: 'Synthetic index learner',
        status: 'active' as const,
        createdBy: 'synthetic-test',
        updatedBy: 'synthetic-test',
        createdAt: new Date(),
        updatedAt: new Date(),
        revision: 0,
      };
      await repository.transaction((tx) => tx.insertUser(row));
      await expect(
        repository.transaction((tx) => tx.insertUser(row)),
      ).rejects.toMatchObject({ code: 'DUPLICATE' });
      await repository.transaction((tx) =>
        tx.insertUser({ ...row, identitySubject: 'without-id-b' }),
      );
      await repository.transaction((tx) =>
        tx.insertUser({
          ...row,
          identitySubject: 'with-id-a',
          employeeId: 'SYN-INDEX',
        }),
      );
      await expect(
        repository.transaction((tx) =>
          tx.insertUser({
            ...row,
            identitySubject: 'with-id-b',
            employeeId: 'SYN-INDEX',
          }),
        ),
      ).rejects.toMatchObject({ code: 'DUPLICATE' });
    });
    it('enforces organization/root/unit indexes and rolls back partial writes', async () => {
      const service = createOrganizationService(repository);
      const { organization, root } = await service.createOrganization(
        {
          code: 'DB_' + randomUUID().replaceAll('-', ''),
          name: 'Synthetic constraint fixture',
          timeZone: 'UTC',
        },
        { actorId: 'synthetic-test' },
      );
      const { id: orgId, ...organizationData } = organization;
      await expect(
        repository.transaction((tx) => tx.insertOrganization(organizationData)),
      ).rejects.toMatchObject({ code: 'DUPLICATE' });
      const { id: rootId, ...rootData } = root;
      await expect(
        repository.transaction((tx) =>
          tx.insertUnit({ ...rootData, code: 'OTHER_ROOT' }),
        ),
      ).rejects.toMatchObject({ code: 'DUPLICATE' });
      const plant = await service.createUnit(
        {
          organizationId: orgId,
          parentId: rootId,
          type: 'plant',
          code: 'SYN_PLANT',
          name: 'Synthetic plant',
          expectedTreeRevision: 0,
        },
        { actorId: 'synthetic-test' },
      );
      const { id: plantId, ...plantData } = plant;
      expect(plantId).not.toBe(rootId);
      await expect(
        repository.transaction((tx) => tx.insertUnit(plantData)),
      ).rejects.toMatchObject({ code: 'DUPLICATE' });
      const rollbackCode = 'ROLLBACK_' + randomUUID().replaceAll('-', '');
      await expect(
        repository.transaction(async (tx) => {
          await tx.insertOrganization({
            ...organizationData,
            code: rollbackCode,
          });
          throw new Error('Synthetic rollback sentinel');
        }),
      ).rejects.toThrow('Synthetic rollback sentinel');
      expect(
        await repository.transaction((tx) =>
          tx.organizationByCode(rollbackCode),
        ),
      ).toBeNull();
    });
  },
);
